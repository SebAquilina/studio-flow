-- Studio Flow — Standard tier additions on top of skill base (0001_init + 0002_analytics)

CREATE TABLE IF NOT EXISTS classes (
  slug TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL,                      -- 'yoga' | 'pilates' | 'breathwork' | 'specials'
  duration_min INTEGER NOT NULL,
  level TEXT NOT NULL,                         -- 'Beginner' | 'Intermediate' | 'All levels' | 'Beginner & up' | 'Pregnant clients only'
  hook TEXT NOT NULL,                          -- one-line description
  description TEXT NOT NULL,                   -- full prose for /classes/[slug]
  what_to_bring TEXT,                          -- "Mat, water" etc
  contraindications TEXT,                      -- "Acute knee injury, recent abdominal surgery"
  capacity INTEGER NOT NULL DEFAULT 12,
  active INTEGER NOT NULL DEFAULT 1,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS instructors (
  slug TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  pronouns TEXT,
  credentials TEXT NOT NULL,                   -- short list, comma-separated
  specialties TEXT NOT NULL,                   -- e.g. "Prenatal · Slow Hatha · Restorative"
  bio_md TEXT NOT NULL,
  classes_taught TEXT NOT NULL,                -- comma-separated class slugs
  privates_eur INTEGER NOT NULL DEFAULT 7000,  -- price for 1-on-1 in cents (€70 = 7000)
  active INTEGER NOT NULL DEFAULT 1,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS class_sessions (
  id TEXT PRIMARY KEY,
  class_slug TEXT NOT NULL,
  instructor_slug TEXT NOT NULL,
  starts_at TEXT NOT NULL,                     -- ISO datetime
  ends_at TEXT NOT NULL,
  capacity INTEGER NOT NULL DEFAULT 12,
  booked INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'open',         -- 'open' | 'full' | 'cancelled'
  notes TEXT,
  FOREIGN KEY (class_slug) REFERENCES classes(slug),
  FOREIGN KEY (instructor_slug) REFERENCES instructors(slug)
);
CREATE INDEX IF NOT EXISTS idx_class_sessions_starts ON class_sessions(starts_at);
CREATE INDEX IF NOT EXISTS idx_class_sessions_class ON class_sessions(class_slug);

CREATE TABLE IF NOT EXISTS bookings (
  id TEXT PRIMARY KEY,
  session_id TEXT NOT NULL,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  party_size INTEGER NOT NULL DEFAULT 1,
  pack_slug TEXT,                              -- 'drop-in' | '5-pack' | '10-pack' | 'monthly' | 'private'
  notes TEXT,
  status TEXT NOT NULL DEFAULT 'requested',    -- 'requested' | 'confirmed' | 'cancelled' | 'no-show'
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  cancelled_at TEXT,
  FOREIGN KEY (session_id) REFERENCES class_sessions(id)
);
CREATE INDEX IF NOT EXISTS idx_bookings_session ON bookings(session_id);
CREATE INDEX IF NOT EXISTS idx_bookings_email ON bookings(email);

CREATE TABLE IF NOT EXISTS class_packs (
  slug TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  price_cents INTEGER NOT NULL,
  classes_included INTEGER,                    -- NULL for unlimited monthly
  validity_days INTEGER,                       -- NULL for monthly
  description TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  sort_order INTEGER NOT NULL DEFAULT 0
);

